import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { findAiCredit, isAiIdentity } from './ai-credit.mjs';

const HOOK = fileURLToPath(new URL('./block-ai-credit.mjs', import.meta.url));
const HEADER =
  '<!-- claude-projects-attribution: {"github_login":"KenEzekiel"} -->\n' +
  '_Requested by **Ken** · [project thread](https://claude.ai/code/project/chan_01?thread=cmsg_01)_\n\n';

const blocked = [
  'Co-Authored-By: Claude Opus 4 <noreply@anthropic.com>',
  'co-authored-by: Claude <someone@example.com>',
  'Co-authored-by: Copilot <copilot@github.com>',
  'Assisted-by: ChatGPT',
  'Claude-Session: https://example.com/abc',
  '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
  '_Generated by [Claude Code](https://claude.ai/code)_',
  'Generated with Claude Code',
  'Written by GitHub Copilot',
  'This PR was created using ChatGPT.',
  'generated by an AI assistant',
  'https://claude.ai/code/session_01VH9VDcH23Fu7bXywMum9dY',
  `${HEADER}## What\n\nFix the header.`,
  '<!-- claude-projects-attribution: {"github_login":"KenEzekiel"} -->\n\nBody',
  '_Requested by **Ken**_\n\nBody',
  'Requested by Ken · project thread',
];

const allowed = [
  'feat: add youtube playlist section\n\nShows the latest sermons.',
  'chore: block AI credit in commits and pull requests',
  'Co-Authored-By: Kenneth Ezekiel <ken35kiel@gmail.com>',
  'Signed-off-by: Kenneth Ezekiel <ken35kiel@gmail.com>',
  'Built with cursor-based pagination, generated by the build script.',
  'Update .claude/settings.json and the Claude Code hooks',
  '## What\n\nFix the header. Ken requested this change.',
];

for (const text of blocked) {
  test(`blocks: ${text.slice(0, 60).replace(/\n/g, ' ')}`, () => {
    assert.notEqual(findAiCredit(text).length, 0);
  });
}
for (const text of allowed) {
  test(`allows: ${text.slice(0, 60).replace(/\n/g, ' ')}`, () => {
    assert.deepEqual(findAiCredit(text), []);
  });
}

test('AI git identities', () => {
  assert.equal(isAiIdentity('Claude', 'noreply@anthropic.com'), true);
  assert.equal(isAiIdentity('Kenneth Ezekiel', 'noreply@anthropic.com'), true);
  assert.equal(isAiIdentity('Claude', 'ken35kiel@gmail.com'), true);
  assert.equal(isAiIdentity('Kenneth Ezekiel', 'ken35kiel@gmail.com'), false);
});

function runHook(tool_name, tool_input) {
  return spawnSync('node', [HOOK], {
    input: JSON.stringify({ tool_name, tool_input, cwd: process.cwd() }),
    encoding: 'utf8',
    env: { ...process.env, GIT_AUTHOR_NAME: 'Kenneth Ezekiel', GIT_AUTHOR_EMAIL: 'ken35kiel@gmail.com', GIT_COMMITTER_NAME: 'Kenneth Ezekiel', GIT_COMMITTER_EMAIL: 'ken35kiel@gmail.com' },
  });
}

test('hook rejects a commit command with an AI trailer', () => {
  const r = runHook('Bash', { command: 'git commit -m "fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"' });
  assert.equal(r.status, 2);
  assert.match(r.stderr, /BLOCKED/);
});

test('hook rejects gh pr create with the footer', () => {
  const r = runHook('Bash', { command: 'gh pr create --title "fix: x" --body "Fix\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"' });
  assert.equal(r.status, 2);
});

test('hook rejects a commit made with an AI identity', () => {
  const r = spawnSync('node', [HOOK], {
    input: JSON.stringify({ tool_name: 'Bash', tool_input: { command: 'git commit -m "fix: x"' }, cwd: process.cwd() }),
    encoding: 'utf8',
    env: { ...process.env, GIT_AUTHOR_NAME: 'Claude', GIT_AUTHOR_EMAIL: 'noreply@anthropic.com' },
  });
  assert.equal(r.status, 2);
  assert.match(r.stderr, /identity/);
});

test('hook rejects GitHub MCP pull request tools with AI credit', () => {
  for (const tool of ['mcp__github__create_pull_request', 'mcp__github__update_pull_request']) {
    const r = runHook(tool, { title: 'fix: x', body: `${HEADER}## What\n\nFix.` });
    assert.equal(r.status, 2, tool);
  }
  assert.equal(runHook('mcp__github__push_files', { message: 'x\n\nCo-Authored-By: Claude <noreply@anthropic.com>' }).status, 2);
});

test('hook allows clean commands and tool calls', () => {
  assert.equal(runHook('Bash', { command: 'git commit -m "fix: keep avatars under the header"' }).status, 0);
  assert.equal(runHook('Bash', { command: 'grep -r "Co-Authored-By: Claude" .' }).status, 0);
  assert.equal(runHook('mcp__github__create_pull_request', { title: 'fix: x', body: '## What\n\nFix.' }).status, 0);
  assert.equal(runHook('mcp__github__add_issue_comment', { body: '_Generated by [Claude Code](https://claude.ai/code)_' }).status, 0);
});
